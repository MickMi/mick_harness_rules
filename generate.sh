#!/bin/bash
set -euo pipefail

# ============================================================
# generate.sh — Single-source rule generator
#
# Reads the canonical source of truth:
#   rules/core.md      (the 10 non-negotiable rules — weak-model optimized)
#   rules/extended.md  (full engineering depth)
#
# Produces IDE/agent-specific rule files into dist/, each assembled
# under one of three profiles:
#   minimal → only project-specific constraints (Anthropic Claude 原生模型 in Claude Code)
#   lean    → core inline + pointer to extended (非原生模型 in Claude Code, AGENTS.md, Copilot, Trae)
#   full    → core + extended fully inline      (Cursor, Windsurf, Cline)
#
# setup.sh symlinks the project-root rule files to dist/<file>, so a
# single edit to core.md / extended.md propagates everywhere after
# re-running this script.
#
# Usage:
#   ./generate.sh            # regenerate all targets
#   ./generate.sh --check    # verify dist/ is up to date (CI guard), no writes
# ============================================================

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; CYAN='\033[0;36m'; NC='\033[0m'
info()  { echo -e "${CYAN}ℹ️  $1${NC}"; }
ok()    { echo -e "${GREEN}✅ $1${NC}"; }
warn()  { echo -e "${YELLOW}⚠️  $1${NC}"; }
fail()  { echo -e "${RED}❌ $1${NC}"; }

HARNESS_ROOT="$(cd "$(dirname "$0")" && pwd)"
CORE="$HARNESS_ROOT/rules/core.md"
EXTENDED="$HARNESS_ROOT/rules/extended.md"
DIST="$HARNESS_ROOT/dist"

CHECK_MODE=false
[ "${1:-}" = "--check" ] && CHECK_MODE=true

for f in "$CORE" "$EXTENDED"; do
    if [ ! -f "$f" ]; then
        fail "Source of truth missing: $f"
        exit 1
    fi
done

# A short, machine-and-human readable "do not edit" banner.
banner() {
    cat <<EOF
<!-- ============================================================ -->
<!-- AUTO-GENERATED by .harness/generate.sh — DO NOT EDIT BY HAND -->
<!-- Edit the source of truth instead:                            -->
<!--   .harness/rules/core.md      (the 10 core rules)            -->
<!--   .harness/rules/extended.md  (full engineering rules)       -->
<!-- Then re-run: .harness/generate.sh                            -->
<!-- ============================================================ -->
EOF
}

# Build one target file body to stdout.
#   $1 = profile (minimal|lean|full)
#   $2 = tool display name (for the intro line)
render() {
    local profile="$1" tool="$2"
    banner
    echo ""
    echo "# 工程规范 · $tool"
    echo ""

    if [ "$profile" = "minimal" ]; then
        # Minimal profile: only rules the tool DOESN'T enforce natively.
        # For strong models (Claude Code) that already have built-in:
        #   - read before edit, plan before act, ask when unclear
        #   - defensive coding, error analysis, self-review
        #   - permission system for dangerous ops
        echo "> 本项目使用 Mick Harness。你的内建能力已覆盖大部分编码规范，以下仅补充你不知道的项目级约束。"
        echo ""
        echo "## 项目级约束"
        echo ""
        echo "**⚡ 前置检查**：开始任何任务前，先看 \`plan.md\` 是否存在。存在则读取它，按其中的步骤逐一执行，每完成一步将 \`[ ]\` 改为 \`[x]\`。不存在则跳过本条，正常工作。"
        echo ""
        echo "**锁死技术栈**：不擅自更换语言/框架/库，不擅自引入新依赖。要换先说明原因并等用户确认。"
        echo ""
        echo "**收尾格式**：完成后报告「做了什么 / 为什么这么做 / 改了哪些文件」，先说业务结果再说技术细节。"
        echo ""
        echo "## 角色协作"
        echo ""
        echo "需要需求评审、测试策略、代码审查时，用户会明确点名对应角色。"
        echo "角色文件见 \`.harness/rules/roles/\`（pm.md / qa.md / reviewer.md / designer.md）。"
        echo ""
        echo "## 详细规范"
        echo ""
        echo "完整工程规范（Git / CI-CD / 测试 / Brain 记忆写入 / Plan-Execute Protocol）见 \`.harness/rules/extended.md\`。"
        echo "需要时主动读取该文件。"
    else
        echo "> 本项目使用 Mick Harness 单源规则体系。下面的「核心铁律」是最高优先级，任何情况不可违反。"
        echo ""
        cat "$CORE"
        echo ""
        if [ "$profile" = "full" ]; then
            echo "---"
            echo ""
            cat "$EXTENDED"
        else
            echo "---"
            echo ""
            echo "## 详细规范"
            echo ""
            echo "完整工程规范（代码哲学 / Git / CI-CD / 测试 / 角色协作）见 \`.harness/rules/extended.md\`。"
            echo "需要时主动读取该文件，不要凭印象编造规范。"
        fi
    fi
}

# target_path | profile | display name
TARGETS=(
    "AGENTS.md|lean|AGENTS.md 通用标准 (Codex / Zed / Aider)"
    "CLAUDE.md|lean|Claude Code"
    ".cursorrules|full|Cursor"
    ".windsurfrules|full|Windsurf"
    ".clinerules|full|Cline / Roo"
    ".github/copilot-instructions.md|lean|GitHub Copilot"
    ".trae/rules.md|lean|Trae"
)

mkdir -p "$DIST"

GENERATED=0
DRIFT=0
for entry in "${TARGETS[@]}"; do
    IFS='|' read -r rel profile name <<< "$entry"
    out="$DIST/$rel"
    mkdir -p "$(dirname "$out")"
    tmp="$(mktemp)"
    render "$profile" "$name" > "$tmp"

    if [ "$CHECK_MODE" = true ]; then
        if [ ! -f "$out" ] || ! diff -q "$tmp" "$out" >/dev/null 2>&1; then
            warn "Out of date: dist/$rel"
            ((DRIFT++))
        fi
        rm -f "$tmp"
    else
        mv "$tmp" "$out"
        ok "Generated: dist/$rel  [$profile]"
        ((GENERATED++))
    fi
done

echo ""
if [ "$CHECK_MODE" = true ]; then
    if [ "$DRIFT" -gt 0 ]; then
        fail "$DRIFT file(s) out of date. Run: .harness/generate.sh"
        exit 1
    fi
    ok "All generated rule files are up to date."
else
    ok "Generated $GENERATED rule files into dist/ from single source."
    info "setup.sh symlinks project-root rule files to these. Edit rules/*.md and re-run to propagate."
fi
